export const land: number[] = [];
export const landSet: Record<number, 1> = {};

MAP.split("|").forEach((row) => {
  const p = row.split(":");
  const y = +p[0];
  p[1].split(",").forEach((seg) => {
    const ab = seg.split("-");
    const a = +ab[0];
    const b = ab.length > 1 ? +ab[1] : a;
    for (let x = a; x <= b; x += 8) {
      land.push(x, y);
      landSet[x * 10000 + y] = 1;
    }
  });
});

/** Pushes [x,y] points for x from x0 to x1 (step 8) at a fixed row y. */
export function run(arr: [number, number][], x0: number, x1: number, y: number) {
  for (let x = x0; x <= x1; x += 8) arr.push([x, y]);
}
